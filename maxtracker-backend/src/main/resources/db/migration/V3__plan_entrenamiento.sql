-- Plan semanal de entrenamiento: qué días de la semana entrena el usuario.
-- Se guarda un historial: cada cambio rige desde su fecha (vigente_desde), así los días pasados se evalúan con el
-- plan que estaba vigente entonces y cambiar el plan no reescribe los fallos anteriores.
-- dias_semana es una máscara de bits ISO-8601: bit 0 = lunes ... bit 6 = domingo (1..127 = al menos un día).
CREATE TABLE plan_entrenamiento (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id    BIGINT                   NOT NULL,
    dias_semana   SMALLINT                 NOT NULL,
    vigente_desde DATE                     NOT NULL,
    creado_en     TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_plan_usuario FOREIGN KEY (usuario_id) REFERENCES usuario (id) ON DELETE CASCADE,
    -- Un solo plan por día: cambiarlo dos veces el mismo día reemplaza el del día. El índice también cubre la FK.
    CONSTRAINT uk_plan_usuario_desde UNIQUE (usuario_id, vigente_desde),
    CONSTRAINT ck_plan_dias CHECK (dias_semana BETWEEN 1 AND 127)
);
