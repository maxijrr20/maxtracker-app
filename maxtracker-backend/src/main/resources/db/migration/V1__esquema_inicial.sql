-- =========================================================
-- MaxTracker - Esquema inicial (Dia 2)
-- Compatible con PostgreSQL (Supabase) y H2 en modo PostgreSQL (tests).
-- =========================================================

CREATE TABLE usuario (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         VARCHAR(255)             NOT NULL,
    password_hash VARCHAR(100)             NOT NULL,
    creado_en     TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_usuario_email UNIQUE (email)
);

-- Ejercicio: copia local de un ejercicio de wger (wger_id) o ejercicio personalizado de un usuario (usuario_id).
-- Asi el historial no depende de que wger este disponible.
CREATE TABLE ejercicio (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    wger_id    BIGINT,
    usuario_id BIGINT,
    nombre     VARCHAR(150)             NOT NULL,
    categoria  VARCHAR(50),
    creado_en  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_ejercicio_wger UNIQUE (wger_id),
    CONSTRAINT uk_ejercicio_usuario_nombre UNIQUE (usuario_id, nombre),
    CONSTRAINT fk_ejercicio_usuario FOREIGN KEY (usuario_id) REFERENCES usuario (id) ON DELETE CASCADE,
    CONSTRAINT ck_ejercicio_origen CHECK (
        (wger_id IS NOT NULL AND usuario_id IS NULL) OR (wger_id IS NULL AND usuario_id IS NOT NULL)
    )
);

CREATE TABLE rutina (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id  BIGINT                   NOT NULL,
    nombre      VARCHAR(100)             NOT NULL,
    descripcion VARCHAR(500),
    creado_en   TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_rutina_usuario FOREIGN KEY (usuario_id) REFERENCES usuario (id) ON DELETE CASCADE
);

CREATE TABLE rutina_ejercicio (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rutina_id             BIGINT   NOT NULL,
    ejercicio_id          BIGINT   NOT NULL,
    orden                 SMALLINT NOT NULL,
    series_objetivo       SMALLINT,
    repeticiones_objetivo SMALLINT,
    CONSTRAINT fk_rutina_ejercicio_rutina FOREIGN KEY (rutina_id) REFERENCES rutina (id) ON DELETE CASCADE,
    CONSTRAINT fk_rutina_ejercicio_ejercicio FOREIGN KEY (ejercicio_id) REFERENCES ejercicio (id),
    -- Sin UNIQUE (rutina_id, orden): al reordenar, Hibernate actualiza filas antes de borrar y lo violaria.
    -- El orden lo mantiene la entidad Rutina.
    CONSTRAINT ck_rutina_ejercicio_orden CHECK (orden > 0),
    CONSTRAINT ck_rutina_ejercicio_series CHECK (series_objetivo IS NULL OR series_objetivo > 0),
    CONSTRAINT ck_rutina_ejercicio_reps CHECK (repeticiones_objetivo IS NULL OR repeticiones_objetivo > 0)
);

CREATE TABLE sesion_entrenamiento (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT                   NOT NULL,
    rutina_id  BIGINT,
    fecha      DATE                     NOT NULL,
    notas      VARCHAR(1000),
    creado_en  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_sesion_usuario FOREIGN KEY (usuario_id) REFERENCES usuario (id) ON DELETE CASCADE,
    CONSTRAINT fk_sesion_rutina FOREIGN KEY (rutina_id) REFERENCES rutina (id) ON DELETE SET NULL
);

CREATE TABLE serie_registro (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sesion_id    BIGINT        NOT NULL,
    ejercicio_id BIGINT        NOT NULL,
    numero_serie SMALLINT      NOT NULL,
    peso_kg      NUMERIC(6, 2) NOT NULL,
    repeticiones SMALLINT      NOT NULL,
    rir          SMALLINT,
    CONSTRAINT fk_serie_sesion FOREIGN KEY (sesion_id) REFERENCES sesion_entrenamiento (id) ON DELETE CASCADE,
    CONSTRAINT fk_serie_ejercicio FOREIGN KEY (ejercicio_id) REFERENCES ejercicio (id),
    CONSTRAINT uk_serie_sesion_ejercicio_numero UNIQUE (sesion_id, ejercicio_id, numero_serie),
    CONSTRAINT ck_serie_numero CHECK (numero_serie > 0),
    CONSTRAINT ck_serie_peso CHECK (peso_kg >= 0),
    CONSTRAINT ck_serie_repeticiones CHECK (repeticiones > 0),
    CONSTRAINT ck_serie_rir CHECK (rir IS NULL OR rir BETWEEN 0 AND 10)
);

-- Indices para las consultas por usuario y de progreso (las FK no se indexan solas en PostgreSQL)
CREATE INDEX ix_rutina_usuario ON rutina (usuario_id);
CREATE INDEX ix_rutina_ejercicio_rutina_orden ON rutina_ejercicio (rutina_id, orden);
CREATE INDEX ix_rutina_ejercicio_ejercicio ON rutina_ejercicio (ejercicio_id);
CREATE INDEX ix_sesion_usuario_fecha ON sesion_entrenamiento (usuario_id, fecha);
CREATE INDEX ix_sesion_rutina ON sesion_entrenamiento (rutina_id);
CREATE INDEX ix_serie_sesion ON serie_registro (sesion_id);
CREATE INDEX ix_serie_ejercicio ON serie_registro (ejercicio_id);
